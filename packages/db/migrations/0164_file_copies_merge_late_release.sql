-- Хвост второго переноса задвоенных чеков (docs/deviations.md п. К-19, О-81; миграция 0160): этапы 1 и 2
-- пакета «Доработки 16.11.2026» вышли на рабочий сайт одним выпуском 17.11.2026, и копии принятых чеков,
-- которые прежний код сделал в минуты выпуска (миграции 0159 и 0160 уже прошли, новый код ещё не был
-- выложен), остались. Здесь функция вызывается ещё раз — с верхней границей: рабочий сайт с новым кодом
-- готов 17.11.2026 в 19:50:20 по Бишкеку. Копии позже границы делал уже не прежний код (например, тот же
-- файл, вручную загруженный в форму денег) — их функция не трогает. В новой базе повтор ничего не меняет.
-- На стенде новый код работал раньше границы (стенд обновляется при слиянии, до выпуска), поэтому там
-- вызов может объединить и файл, вручную загруженный в форму денег до границы: данные стенда тестовые,
-- файл остаётся у контрагента и у записи одной строкой. Предел ожидания блокировок — как у 0157, 0159 и 0160.
SET LOCAL lock_timeout = '10s';--> statement-breakpoint
DO $$
BEGIN
  RAISE NOTICE 'file_copies_merge_late (0164): %',
    app.file_copies_merge_late('2026-11-17 19:50:20+06'::timestamptz);
END
$$;
