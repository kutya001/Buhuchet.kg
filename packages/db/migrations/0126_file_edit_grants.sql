-- «Изменить файл» (прототип v95, просьба заказчика 13.11.2026): название файла меняют в окне, а при
-- замене файла к записи переходят ключ хранилища, размер и тип загрузки-замены, и ставится отметка
-- «заменён: кто и когда». Миграция 0037 разрешила роли приложения менять у файла только состояние,
-- контрагента, примечание и служебные поля — добавляем эти столбцы. Источник и автора загрузки
-- по-прежнему не меняет никто, кроме миграций; удалённый файл не меняется (политика files_update_guard),
-- а ключ хранилища остаётся внутри папки своей организации (ограничение files_key_check).
GRANT UPDATE (name, content_type, size_bytes, storage_key, replaced_at, replaced_by)
  ON TABLE files TO buhuchet_app;
