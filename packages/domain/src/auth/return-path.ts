/*
 * Возврат на страницу после входа (ТЗ «Лендинг» → «Кто что видит по адресу»: «Гость открыл прямую
 * ссылку на страницу программы (например, на отчёт из сообщения Telegram): открывается страница входа,
 * а после входа — та самая страница»). Адрес приходит в строке запроса страницы входа, поэтому
 * принимается только путь программы этого же сайта: иначе ссылка вида /login?next=//чужой.сайт
 * уводила бы вошедшего на чужую страницу.
 */

/** Параметр страницы входа с адресом возврата: `/login?next=/app/reports/all`. */
export const RETURN_PARAM = 'next';

/** Предел длины адреса возврата: длиннее адреса страницы программы не бывает. */
export const RETURN_PATH_MAX = 512;

/**
 * Адрес возврата, если это страница программы (`/app` или `/app/…`, с параметрами и якорем); иначе
 * null. Без схемы и хоста, без `//`, обратной косой черты, управляющих символов и `..`.
 */
export function safeReturnPath(value: string | null | undefined): string | null {
  if (!value || value.length > RETURN_PATH_MAX) return null;
  if (!/^\/app(?:[/?#]|$)/.test(value)) return null;
  // eslint-disable-next-line no-control-regex -- управляющие символы в адресе — признак подделки
  if (/[\\\u0000-\u001f\u007f]|\/\/|(?:^|\/)\.\.?(?:[/?#]|$)/.test(value)) return null;
  return value;
}
